export function buildImagePrompt(topic: string): string {
  return `A professional, modern hero image for a business blog post about: "${topic}".

Visual style: clean, editorial photography or minimal flat illustration.
Subject matter: global business, entrepreneurship, financial documents, laptop with business dashboard, diverse professional, US skyline or Capitol building, modern office.
Mood: trustworthy, empowering, international.
No text, no letters, no words, no numbers anywhere in the image.
Wide landscape format, high quality, sharp focus.`;
}
